// Centralized Mission Operations Zustand Store synchronized across all 10 modules
import { create } from 'zustand';
import { getInitialTelemetry, generateInitialTelemetryHistory } from '../services/telemetryService';
import { INITIAL_ALERTS, evaluateTelemetryThresholds } from '../services/alertService';
import { INITIAL_TIMELINE_EVENTS } from '../data/timelineEvents';
import { SATELLITE_CATALOG } from '../data/satelliteCatalog';
import { FAILURE_SCENARIOS } from '../data/failureScenarios';
import { computeNextSimulationStep } from '../services/simulationEngine';
import { computePlanetaryDistancesFromEarth } from '../services/orbitalService';
import { formatMET } from '../utils/formatters';
import { useSettingsStore } from './settingsStore';

const INITIAL_SPACECRAFT = {
  name: 'ORION MPCV-04 (ENDURANCE)',
  missionName: 'ARTEMIS-IV CISLUNAR OPERATIONS',
  missionId: 'NASA-ARTEMIS-IV // OM-04',
  status: 'NOMINAL',
  healthScore: 100,
  distanceFromEarthKm: 246840.0,
  distanceFromMoonKm: 137560.0,
  orbitalVelocityKms: 1.48,
  altitudeKm: 240469,
  missionProgressPct: 64.2,
  position: { x: 184200, y: 14850, z: -162400 },
  velocity: { vx: 0.92, vy: 0.14, vz: -1.15 },
  headingDeg: 128.4,
  accelerationG: 0.002,
};

const INITIAL_ORBITAL_PARAMS = {
  centralBody: 'EARTH',
  semiMajorAxisKm: 42164,
  eccentricity: 0.32,
  inclinationDeg: 28.5,
  raanDeg: 45.0,
  argPerigeeDeg: 30.0,
  burnDeltaVMps: 0,
  showGrid: true,
  showPredictedPath: true,
  cameraMode: 'FREE',
};

export const useMissionStore = create((set, get) => ({
  missionStatus: 'RUNNING', // 'RUNNING' | 'PAUSED' | 'ABORTED' | 'EMERGENCY'
  missionPhase: 'TRANSLUNAR COAST (PHASE 3)',
  metSeconds: 148320,
  lastTelemetryUpdateUtc: new Date().toISOString().slice(11, 19) + ' UTC',
  simSpeed: 1,
  autoMonitoring: true,
  activeEmergency: null,
  emergencyPaused: false,
  recoveryInProgress: false,
  recoveryProgress: 0,

  spacecraft: { ...INITIAL_SPACECRAFT },
  telemetry: getInitialTelemetry(),
  telemetryHistory: generateInitialTelemetryHistory(148320),
  orbitalParams: { ...INITIAL_ORBITAL_PARAMS },
  alerts: [...INITIAL_ALERTS],
  timelineEvents: [...INITIAL_TIMELINE_EVENTS],
  satellites: [...SATELLITE_CATALOG],

  selectedPlanetId: 'mars',
  followSpacecraftCamera: false,
  showEarthDistanceVector: true,
  planetaryDistances: computePlanetaryDistancesFromEarth(148320),
  selectedSatelliteId: 'SAT-001',
  trackingCameraLocked: false,
  selectedTimelineEventId: 'EVT-05',
  selectedScenarioId: 'SCEN-01',

  // Simulation Tick Action
  tickSimulation: () => {
    const state = get();
    if (state.missionStatus === 'PAUSED' || state.missionStatus === 'ABORTED') {
      return;
    }

    const next = computeNextSimulationStep(state);
    const thresholds = useSettingsStore.getState().thresholds;
    const autoGeneratedAlerts = state.autoMonitoring
      ? evaluateTelemetryThresholds(next.telemetry, thresholds, state.alerts, next.metSeconds)
      : [];

    // Update satellite orbital coordinates dynamically
    const updatedSatellites = state.satellites.map((sat, idx) => {
      const angularRate = (0.04 * state.simSpeed) / Math.max(1, sat.periodMin / 90);
      const nextLat = Number((Math.sin(next.metSeconds * 0.008 + sat.phaseOffset + idx) * sat.inclinationDeg).toFixed(2));
      const nextLon = Number((((sat.lon + angularRate * 12) + 540) % 360 - 180).toFixed(2));
      return {
        ...sat,
        lat: nextLat,
        lon: nextLon,
      };
    });

    set({
      metSeconds: next.metSeconds,
      lastTelemetryUpdateUtc: new Date().toISOString().slice(11, 19) + ' UTC',
      spacecraft: next.spacecraft,
      telemetry: next.telemetry,
      telemetryHistory: [...state.telemetryHistory.slice(-29), next.snapshot],
      activeEmergency: next.activeEmergency,
      recoveryInProgress: next.recoveryInProgress,
      recoveryProgress: next.recoveryProgress,
      missionStatus: next.activeEmergency ? 'EMERGENCY' : 'RUNNING',
      alerts: autoGeneratedAlerts.length > 0 ? [...autoGeneratedAlerts, ...state.alerts].slice(0, 50) : state.alerts,
      satellites: updatedSatellites,
      planetaryDistances: computePlanetaryDistancesFromEarth(next.metSeconds),
    });
  },

  // Mission Control Actions
  startMission: () => set({ missionStatus: get().activeEmergency ? 'EMERGENCY' : 'RUNNING' }),
  pauseMission: () => set({ missionStatus: 'PAUSED' }),
  resumeMission: () => set({ missionStatus: get().activeEmergency ? 'EMERGENCY' : 'RUNNING' }),
  abortSimulation: () => {
    const nowUtc = new Date().toISOString().slice(11, 19) + ' UTC';
    const metStr = formatMET(get().metSeconds);
    const abortAlert = {
      id: `ABORT-${Date.now()}`,
      timestamp: nowUtc,
      met: metStr,
      severity: 'EMERGENCY',
      category: 'FLIGHT DIRECTOR',
      subsystem: 'MISSION CONTROL',
      title: 'Mission Simulation Aborted by Flight Director',
      message: 'Flight Director commanded simulation abort; spacecraft placed in safe hold configuration.',
      acknowledged: false,
      resolved: false,
      details: 'All maneuvering thrusters inhibited; telemetry frozen for post-abort review.',
      recommendedAction: 'Click Reset Mission or Resume Mission to return to active operations.'
    };
    set((s) => ({
      missionStatus: 'ABORTED',
      spacecraft: { ...s.spacecraft, status: 'ABORT' },
      alerts: [abortAlert, ...s.alerts],
    }));
  },

  resetMission: () => {
    const defaultSpeed = useSettingsStore.getState().defaultSimSpeed || 1;
    set({
      missionStatus: 'RUNNING',
      missionPhase: 'TRANSLUNAR COAST (PHASE 3)',
      metSeconds: 148320,
      simSpeed: defaultSpeed,
      activeEmergency: null,
      emergencyPaused: false,
      recoveryInProgress: false,
      recoveryProgress: 0,
      spacecraft: { ...INITIAL_SPACECRAFT },
      telemetry: getInitialTelemetry(),
      telemetryHistory: generateInitialTelemetryHistory(148320),
      orbitalParams: { ...INITIAL_ORBITAL_PARAMS },
      alerts: [...INITIAL_ALERTS],
      timelineEvents: [...INITIAL_TIMELINE_EVENTS],
      satellites: [...SATELLITE_CATALOG],
      planetaryDistances: computePlanetaryDistancesFromEarth(148320),
    });
  },

  setSimSpeed: (speed) => set({ simSpeed: Number(speed) || 1 }),
  toggleAutoMonitoring: () => set((s) => ({ autoMonitoring: !s.autoMonitoring })),

  // Scenario / Failure Simulation Actions
  setSelectedScenarioId: (id) => set({ selectedScenarioId: id }),

  triggerScenario: (scenarioId) => {
    const state = get();
    const scenario = FAILURE_SCENARIOS.find((s) => s.id === (scenarioId || state.selectedScenarioId)) || FAILURE_SCENARIOS[0];
    const d = scenario.telemetryDelta || {};

    const power = { ...state.telemetry.power };
    const propulsion = { ...state.telemetry.propulsion };
    const thermal = { ...state.telemetry.thermal };
    const comms = { ...state.telemetry.comms };
    const lifeSupport = { ...state.telemetry.lifeSupport };
    const sc = { ...state.spacecraft };

    if (d.o2LevelPct) lifeSupport.o2LevelPct = Math.max(75, Number((lifeSupport.o2LevelPct + d.o2LevelPct).toFixed(1)));
    if (d.cabinPressureKpa) lifeSupport.cabinPressureKpa = Math.max(78, Number((lifeSupport.cabinPressureKpa + d.cabinPressureKpa).toFixed(1)));
    if (d.engineTempC) {
      propulsion.engineTempC = Number((propulsion.engineTempC + d.engineTempC).toFixed(1));
      thermal.engineTempC = propulsion.engineTempC;
    }
    if (d.propellantPressurePsi) propulsion.propellantPressurePsi = Number((propulsion.propellantPressurePsi + d.propellantPressurePsi).toFixed(1));
    if (d.fuelRemainingPct) propulsion.fuelRemainingPct = Math.max(18, Number((propulsion.fuelRemainingPct + d.fuelRemainingPct).toFixed(1)));
    if (d.signalStrengthDbm) comms.signalStrengthDbm = Number((comms.signalStrengthDbm + d.signalStrengthDbm).toFixed(1));
    if (d.signalPct) comms.signalPct = Math.max(10, Number((comms.signalPct + d.signalPct).toFixed(1)));
    if (d.txRateMbps) comms.txRateMbps = Math.max(0.5, Number((comms.txRateMbps + d.txRateMbps).toFixed(1)));
    if (d.downSpeedMbps) comms.downSpeedMbps = Math.max(0.4, Number((comms.downSpeedMbps + d.downSpeedMbps).toFixed(1)));
    if (d.latencyMs) comms.latencyMs = comms.latencyMs + d.latencyMs;
    if (d.batteryPct) power.batteryPct = Math.max(18, Number((power.batteryPct + d.batteryPct).toFixed(1)));
    if (d.batteryVoltage) power.batteryVoltage = Math.max(92, Number((power.batteryVoltage + d.batteryVoltage).toFixed(1)));
    if (d.powerConsumptionKw) power.powerConsumptionKw = Number((power.powerConsumptionKw + d.powerConsumptionKw).toFixed(1));
    if (d.solarOutputKw) power.solarOutputKw = Math.max(2.5, Number((power.solarOutputKw + d.solarOutputKw).toFixed(1)));
    if (d.cabinTempC) {
      thermal.cabinTempC = Number((thermal.cabinTempC + d.cabinTempC).toFixed(1));
      lifeSupport.cabinTempC = thermal.cabinTempC;
    }
    if (d.externalTempC) thermal.externalTempC = Number((thermal.externalTempC + d.externalTempC).toFixed(1));
    if (d.headingDeg) sc.headingDeg = Number(((sc.headingDeg + d.headingDeg) % 360).toFixed(1));
    if (d.accelerationG) sc.accelerationG = Number(d.accelerationG.toFixed(3));

    // Set subsystem status badges
    if (scenario.subsystem === 'LIFE SUPPORT') {
      lifeSupport.crewStatus = 'EMERGENCY PROTOCOL';
      lifeSupport.filtrationStatus = 'HIGH-FLOW OVERRIDE';
    } else if (scenario.subsystem === 'PROPULSION') {
      propulsion.status = 'FAULT / ISOLATED';
    } else if (scenario.subsystem === 'COMMUNICATION') {
      comms.antennaStatus = 'OMNI S-BAND FALLBACK';
    } else if (scenario.subsystem === 'POWER') {
      power.status = 'BUS FAULT / LOAD SHED';
    } else if (scenario.subsystem === 'THERMAL') {
      thermal.protectionStatus = 'COOLANT LOOP FAULT';
    }

    sc.status = scenario.severity === 'EMERGENCY' ? 'CRITICAL' : 'WARNING';
    sc.healthScore = scenario.severity === 'EMERGENCY' ? 62 : 76;

    const nowUtc = new Date().toISOString().slice(11, 19) + ' UTC';
    const metStr = formatMET(state.metSeconds);
    const emergencyAlert = {
      id: `EMERG-${scenario.code}-${Date.now()}`,
      timestamp: nowUtc,
      met: metStr,
      severity: scenario.severity,
      category: scenario.subsystem,
      subsystem: scenario.code,
      title: `EMERGENCY TRIGGERED: ${scenario.name}`,
      message: scenario.warningMessages[0],
      acknowledged: false,
      resolved: false,
      details: `${scenario.description} Initial Condition: ${scenario.initialConditions}`,
      recommendedAction: scenario.recoveryOptions.join(' -> ')
    };

    // Also mark current timeline event as DELAYED if emergency is active
    const updatedTimeline = state.timelineEvents.map((evt) =>
      evt.status === 'IN PROGRESS'
        ? { ...evt, status: 'DELAYED', actualTimeLabel: 'HOLD (EMERGENCY)' }
        : evt
    );

    set({
      selectedScenarioId: scenario.id,
      activeEmergency: scenario,
      emergencyPaused: false,
      recoveryInProgress: false,
      recoveryProgress: 0,
      missionStatus: 'EMERGENCY',
      spacecraft: sc,
      telemetry: { power, propulsion, thermal, comms, lifeSupport },
      alerts: [emergencyAlert, ...state.alerts],
      timelineEvents: updatedTimeline,
    });
  },

  pauseEmergency: () => set((s) => ({ emergencyPaused: !s.emergencyPaused })),

  executeRecovery: () => {
    const state = get();
    if (!state.activeEmergency) return;
    const nowUtc = new Date().toISOString().slice(11, 19) + ' UTC';
    const metStr = formatMET(state.metSeconds);
    const recoveryAlert = {
      id: `REC-${Date.now()}`,
      timestamp: nowUtc,
      met: metStr,
      severity: 'INFORMATIONAL',
      category: 'RECOVERY SEQUENCE',
      subsystem: state.activeEmergency.code,
      title: `Executing Automated Recovery: ${state.activeEmergency.name}`,
      message: `Recovery sequence initiated: ${state.activeEmergency.recoveryOptions[0]}`,
      acknowledged: true,
      resolved: false,
      details: state.activeEmergency.recoveryOptions.join(' | '),
      recommendedAction: 'Monitoring telemetry stabilization back to nominal envelope.'
    };

    set({
      emergencyPaused: false,
      recoveryInProgress: true,
      recoveryProgress: 20,
      missionStatus: 'RUNNING',
      alerts: [recoveryAlert, ...state.alerts],
    });
  },

  restoreNormalConditions: () => {
    const state = get();
    const nowUtc = new Date().toISOString().slice(11, 19) + ' UTC';
    const metStr = formatMET(state.metSeconds);
    const resolvedAlerts = state.alerts.map((a) =>
      a.severity === 'EMERGENCY' || a.severity === 'CRITICAL'
        ? { ...a, acknowledged: true, resolved: true }
        : a
    );
    const restoreLog = {
      id: `NOM-${Date.now()}`,
      timestamp: nowUtc,
      met: metStr,
      severity: 'INFORMATIONAL',
      category: 'SYSTEM RESTORE',
      subsystem: 'ALL SUBSYSTEMS',
      title: 'All Spacecraft Subsystems Restored to Nominal Envelope',
      message: 'Emergency conditions cleared; ECLSS, EPS, Propulsion, Thermal, and GNC verified nominal.',
      acknowledged: true,
      resolved: true,
      details: 'Spacecraft health score restored to 100%.',
      recommendedAction: 'Resume standard mission timeline monitoring.'
    };
    const restoredTimeline = state.timelineEvents.map((evt) =>
      evt.status === 'DELAYED'
        ? { ...evt, status: 'IN PROGRESS', actualTimeLabel: 'IN PROGRESS' }
        : evt
    );

    set({
      activeEmergency: null,
      emergencyPaused: false,
      recoveryInProgress: false,
      recoveryProgress: 0,
      missionStatus: 'RUNNING',
      spacecraft: {
        ...state.spacecraft,
        status: 'NOMINAL',
        healthScore: 100,
        headingDeg: 128.4,
        accelerationG: 0.002,
      },
      telemetry: getInitialTelemetry(),
      alerts: [restoreLog, ...resolvedAlerts],
      timelineEvents: restoredTimeline,
    });
  },

  // Orbital Trajectory Actions
  updateOrbitalParam: (key, value) =>
    set((s) => ({
      orbitalParams: {
        ...s.orbitalParams,
        [key]: value,
      },
    })),

  resetOrbitalParams: () => set({ orbitalParams: { ...INITIAL_ORBITAL_PARAMS } }),

  // Selection & Camera Actions
  setSelectedPlanetId: (id) => set({ selectedPlanetId: id }),
  setFollowSpacecraftCamera: (val) => set({ followSpacecraftCamera: Boolean(val) }),
  setShowEarthDistanceVector: (val) => set({ showEarthDistanceVector: Boolean(val) }),
  setSelectedSatelliteId: (id) => set({ selectedSatelliteId: id }),
  setTrackingCameraLocked: (val) => set({ trackingCameraLocked: Boolean(val) }),
  setSelectedTimelineEventId: (id) => set({ selectedTimelineEventId: id }),

  jumpToTimelineEvent: (eventId) => {
    const state = get();
    const target = state.timelineEvents.find((e) => e.id === eventId);
    if (!target) return;
    const updatedEvents = state.timelineEvents.map((evt) => {
      if (evt.sequence < target.sequence) {
        return { ...evt, status: 'COMPLETED', actualTimeLabel: evt.scheduledTimeLabel };
      }
      if (evt.sequence === target.sequence) {
        return { ...evt, status: 'IN PROGRESS', actualTimeLabel: 'IN PROGRESS' };
      }
      return { ...evt, status: 'UPCOMING', actualTimeLabel: 'SCHEDULED' };
    });
    const ratio = Math.min(0.99, Math.max(0.02, target.sequence / state.timelineEvents.length));
    const nextDistEarth = Number((ratio * 380000).toFixed(1));
    set({
      selectedTimelineEventId: eventId,
      metSeconds: target.scheduledMetSeconds,
      missionPhase: target.phase,
      timelineEvents: updatedEvents,
      spacecraft: {
        ...state.spacecraft,
        distanceFromEarthKm: nextDistEarth,
        distanceFromMoonKm: Number(Math.max(130, 384400 - nextDistEarth).toFixed(1)),
        missionProgressPct: Number((ratio * 100).toFixed(1)),
      },
    });
  },

  toggleTimelineEventDelay: (eventId) => {
    set((s) => ({
      timelineEvents: s.timelineEvents.map((evt) => {
        if (evt.id !== eventId) return evt;
        const nextStatus = evt.status === 'DELAYED' ? 'UPCOMING' : 'DELAYED';
        return {
          ...evt,
          status: nextStatus,
          actualTimeLabel: nextStatus === 'DELAYED' ? 'DELAYED (+00:45:00)' : 'SCHEDULED',
        };
      }),
    }));
  },

  // Manual Life Support Override Actions
  boostOxygenSupply: () => {
    set((s) => ({
      telemetry: {
        ...s.telemetry,
        lifeSupport: {
          ...s.telemetry.lifeSupport,
          o2LevelPct: Math.min(100, Number((s.telemetry.lifeSupport.o2LevelPct + 3.5).toFixed(1))),
          cabinPressureKpa: Math.min(101.8, Number((s.telemetry.lifeSupport.cabinPressureKpa + 2.2).toFixed(1))),
        },
      },
    }));
  },

  purgeCo2Scrubber: () => {
    set((s) => ({
      telemetry: {
        ...s.telemetry,
        lifeSupport: {
          ...s.telemetry.lifeSupport,
          co2Ppm: Math.max(380, s.telemetry.lifeSupport.co2Ppm - 140),
          filtrationStatus: 'PURGE BOOST (99.9% EFF)',
        },
      },
    }));
  },

  // Alert Management Actions
  acknowledgeAlert: (alertId) =>
    set((s) => ({
      alerts: s.alerts.map((a) => (a.id === alertId ? { ...a, acknowledged: true } : a)),
    })),

  resolveAlert: (alertId) =>
    set((s) => ({
      alerts: s.alerts.map((a) =>
        a.id === alertId ? { ...a, acknowledged: true, resolved: true } : a
      ),
    })),

  acknowledgeAllAlerts: () =>
    set((s) => ({
      alerts: s.alerts.map((a) => ({ ...a, acknowledged: true })),
    })),

  clearResolvedAlerts: () =>
    set((s) => ({
      alerts: s.alerts.filter((a) => !a.resolved),
    })),
}));
